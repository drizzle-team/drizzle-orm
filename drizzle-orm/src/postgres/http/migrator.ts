import type { MigrationConfig, MigratorInitFailResponse } from '~/migrator.ts';
import { readMigrationFiles } from '~/migrator.ts';
import type { AnyRelations } from '~/relations.ts';
import { runAsyncProgram } from '~/runtime/async.ts';
import { migrate as migrateProgram } from '~/up-migrations/pg-program.ts';
import { pgMigrationRunner } from '~/up-migrations/pg.ts';
import type { PostgresHttpDatabase } from './driver.ts';
import type { PostgresNeonHttpDatabase } from './neon.ts';

/**
 * This function reads migrationFolder and execute each unapplied migration and mark it as executed in database
 *
 * @param db - drizzle db instance
 * @param config - path to migration folder generated by drizzle-kit
 */
export function migrate<TRelations extends AnyRelations>(
	db: PostgresHttpDatabase<TRelations> | PostgresNeonHttpDatabase<TRelations>,
	config: MigrationConfig,
): Promise<void | MigratorInitFailResponse> {
	const migrations = readMigrationFiles(config);
	// HTTP has no interactive transactions: statements apply atomically as one batch
	return runAsyncProgram(() => migrateProgram(migrations, pgMigrationRunner(db, 'batch'), config));
}

import * as Effect from 'effect/Effect';
import { MigratorInitError } from '~/effect-core/errors.ts';
import type { MigrationConfig, MigratorInitFailResponse } from '~/migrator.ts';
import { readMigrationFiles } from '~/migrator.ts';
import type { AnyRelations } from '~/relations.ts';
import { runEffectProgram } from '~/runtime/effect.ts';
import { migrate as migrateProgram } from '~/up-migrations/pg-program.ts';
import type { EffectPostgresHttpDatabase } from './driver.ts';
import type { EffectPostgresNeonHttpDatabase } from './neon.ts';

/**
 * This function reads migrationFolder and execute each unapplied migration and mark it as executed in database
 *
 * HTTP has no interactive transactions: the statements of a migration apply atomically as one batch
 *
 * @param db - drizzle db instance
 * @param config - path to migration folder generated by drizzle-kit
 */
export const migrate = Effect.fn('migrate')(function*<TRelations extends AnyRelations>(
	db: EffectPostgresHttpDatabase<TRelations> | EffectPostgresNeonHttpDatabase<TRelations>,
	config: MigrationConfig,
) {
	const migrations = readMigrationFiles(config);
	const { session } = db;

	const initFailure = yield* runEffectProgram<
		void | MigratorInitFailResponse,
		Effect.Error<ReturnType<typeof session.atomically>>,
		never
	>(() =>
		migrateProgram(migrations, {
			execute: (query) => session.execute(query),
			objects: (query) => session.objects(query),
			atomically: (statements) => session.atomically(statements),
		}, config)
	);

	if (initFailure) return yield* new MigratorInitError({ exitCode: initFailure.exitCode });
});
